-- Track codes scanned when a warehouse row is handed over.
-- One goods row (a weight) can contain many parcels, each with its own code.
-- Codes stay on the row after payment is removed.

create table public.good_tracks (
  id bigint generated by default as identity primary key,
  good_id bigint not null references public.goods (id) on delete cascade,
  code text not null,
  created_at timestamptz not null default now(),
  constraint good_tracks_code_len check (char_length(code) between 1 and 120),
  constraint good_tracks_good_code_key unique (good_id, code)
);

create index good_tracks_good_id_idx
  on public.good_tracks (good_id, created_at);

alter table public.good_tracks enable row level security;
